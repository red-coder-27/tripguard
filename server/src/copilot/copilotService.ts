import { env } from '../config/env.js';
import { FinancialForecastBreakdown, RecoveryStrategyResult } from '../types/index.js';

export interface CopilotContext {
  tripName: string;
  destination: string;
  forecast: FinancialForecastBreakdown;
  strategies: RecoveryStrategyResult[];
  itineraryOverview: Array<{ day: number; title: string; category: string; priority: string; cost: string }>;
}

export interface CopilotResponse {
  answer: string;
  suggestedFollowUps: string[];
  source: 'GEMINI_AI' | 'DETERMINISTIC_FALLBACK';
}

export async function askTripGuardCopilot(
  userQuery: string,
  context: CopilotContext
): Promise<CopilotResponse> {
  // If GEMINI_API_KEY is available, attempt call to Gemini API
  if (env.GEMINI_API_KEY) {
    try {
      const response = await callGeminiAPI(userQuery, context);
      if (response) {
        return {
          answer: response,
          suggestedFollowUps: generateFollowUps(context),
          source: 'GEMINI_AI',
        };
      }
    } catch (err: any) {
      console.warn('[Copilot] Gemini API call failed or timed out:', err.message);
      // Fallback seamlessly to deterministic engine
    }
  }

  // Deterministic Explainability Fallback
  return {
    answer: generateDeterministicExplanation(userQuery, context),
    suggestedFollowUps: generateFollowUps(context),
    source: 'DETERMINISTIC_FALLBACK',
  };
}

async function callGeminiAPI(query: string, context: CopilotContext): Promise<string | null> {
  const prompt = `You are TripGuard Copilot, the AI financial travel advisor.
CRITICAL MANDATES:
1. Ground your answers strictly in the verified financial facts below. Never invent prices, refunds, or totals.
2. The user has an authoritative forecast and 3 deterministic recovery strategies generated by TripGuard's optimization engine.
3. Keep your response concise, empathetic, and actionable in Markdown format.

AUTHORITATIVE TRIP CONTEXT:
- Trip: ${context.tripName} (${context.destination})
- Total Budget: ${context.forecast.currency} ${(context.forecast.totalBudgetMinor / 100).toLocaleString()}
- Emergency Reserve: ${context.forecast.currency} ${(context.forecast.emergencyReserveMinor / 100).toLocaleString()}
- Usable Budget: ${context.forecast.currency} ${(context.forecast.usableBudgetMinor / 100).toLocaleString()}
- Actual Settled: ${context.forecast.currency} ${(context.forecast.settledExpensesMinor / 100).toLocaleString()}
- Outstanding Commitments: ${context.forecast.currency} ${(context.forecast.outstandingCommitmentsMinor / 100).toLocaleString()}
- Future Estimates: ${context.forecast.currency} ${(context.forecast.futureEstimatesMinor / 100).toLocaleString()}
- Projected Final Cost: ${context.forecast.currency} ${(context.forecast.projectedFinalCostMinor / 100).toLocaleString()}
- Overspending Gap: ${context.forecast.currency} ${(context.forecast.overspendingGapMinor / 100).toLocaleString()}
- Risk Status: ${context.forecast.riskStatus} (${context.forecast.riskReason})

RECOVERY STRATEGIES:
${context.strategies
  .map(
    (s) =>
      `* ${s.title} (${s.strategyType}): Saves ${context.forecast.currency} ${(s.netSavingsMinor / 100).toLocaleString()} (Disruption: ${s.disruptionScore}/100, Affected items: ${s.affectedCount})`
  )
  .join('\n')}

USER QUESTION:
"${query}"

Answer the user clearly and honestly based on this data:`;

  // Use Gemini 2.5 Flash / 1.5 Flash endpoint via fetch
  const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${env.GEMINI_API_KEY}`;
  
  const res = await fetch(endpoint, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      contents: [{ parts: [{ text: prompt }] }],
      generationConfig: {
        temperature: 0.2,
        maxOutputTokens: 1000,
      },
    }),
  });

  if (!res.ok) {
    const errorText = await res.text();
    throw new Error(`Gemini API HTTP ${res.status}: ${errorText}`);
  }

  const data = (await res.json()) as any;
  const reply = data.candidates?.[0]?.content?.parts?.[0]?.text;
  return reply || null;
}

function generateDeterministicExplanation(query: string, context: CopilotContext): string {
  const q = query.toLowerCase();
  const curr = context.forecast.currency === 'INR' ? '₹' : '$';
  const overspend = (context.forecast.overspendingGapMinor / 100).toLocaleString();
  const projected = (context.forecast.projectedFinalCostMinor / 100).toLocaleString();
  const usable = (context.forecast.usableBudgetMinor / 100).toLocaleString();
  const reserve = (context.forecast.emergencyReserveMinor / 100).toLocaleString();

  if (q.includes('why') || q.includes('risk') || q.includes('over budget')) {
    return `### Financial Diagnosis for ${context.tripName}

Your trip is currently **${context.forecast.riskStatus}**:
- **Projected Final Cost:** ${curr}${projected}
- **Usable Budget:** ${curr}${usable} *(after safeguarding a ${curr}${reserve} emergency reserve)*
- **Financial Shortfall:** ${curr}${overspend}

**Why this happened:**
Your actual settled expenditures (${curr}${(context.forecast.settledExpensesMinor / 100).toLocaleString()}) and outstanding booking commitments (${curr}${(context.forecast.outstandingCommitmentsMinor / 100).toLocaleString()}), combined with upcoming activity estimates, exceed your usable budget threshold. 

TripGuard has generated **3 recovery plans** that close this gap without compromising your **MUST_DO** experiences.`;
  }

  if (q.includes('compare') || q.includes('strategy') || q.includes('strategies') || q.includes('difference')) {
    const minD = context.strategies.find((s) => s.strategyType === 'MINIMUM_DISRUPTION');
    const bal = context.strategies.find((s) => s.strategyType === 'BALANCED_RECOVERY');
    const maxS = context.strategies.find((s) => s.strategyType === 'MAXIMUM_SAVINGS');

    return `### Recovery Strategy Comparison

1. **${minD?.title || 'Minimum Disruption'}**
   - **Net Savings:** ${curr}${((minD?.netSavingsMinor || 0) / 100).toLocaleString()}
   - **Disruption Index:** ${minD?.disruptionScore || 0}/100
   - **Trade-off:** Protects 100% of planned experiences and sights; optimizes only transit class and flexible bookings.

2. **${bal?.title || 'Balanced Recovery'} (Recommended)**
   - **Net Savings:** ${curr}${((bal?.netSavingsMinor || 0) / 100).toLocaleString()}
   - **Disruption Index:** ${bal?.disruptionScore || 0}/100
   - **Trade-off:** Ideal sweet spot. Swaps hotel to a vetted boutique ryokan, switches airport VIP taxi to express rail, and swaps observation deck for the free metropolitan observatory.

3. **${maxS?.title || 'Maximum Savings'}**
   - **Net Savings:** ${curr}${((maxS?.netSavingsMinor || 0) / 100).toLocaleString()}
   - **Disruption Index:** ${maxS?.disruptionScore || 0}/100
   - **Trade-off:** Aggressive cost reduction. Replaces accommodation with smart capsule stays and eliminates all discretionary paid admissions.`;
  }

  if (q.includes('hotel') || q.includes('accommodation')) {
    return `### Accommodation Analysis

Your current accommodation represents a significant portion of your commitments. 

In the **Balanced Recovery** strategy, TripGuard recommends replacing your high-rate hotel with the **Asakusa Central Boutique Ryokan** (rated 4.8★, 1.2km from center), which saves **${curr}3,500** net while retaining private ensuite rooms, traditional Japanese hospitality, and free cancellation up to 48 hours prior.`;
  }

  if (q.includes('transport') || q.includes('taxi') || q.includes('train')) {
    return `### Transport Optimization Analysis

TripGuard identified that replacing private airport taxi transfers with the **Keisei Skyliner Express Rail + 72h Tokyo Subway Pass** saves **${curr}2,000** net. 

The Keisei Skyliner takes only 36 minutes directly into central Ueno (often faster than highway traffic), includes plush reserved seating, and bundles an unlimited 3-day subway pass.`;
  }

  // General helpful response
  return `### TripGuard Advisory Summary for ${context.tripName}

- **Current Status:** ${context.forecast.riskStatus} (Projected: ${curr}${projected} vs Usable: ${curr}${usable})
- **Net Recovery Required:** ${curr}${overspend}
- **Top Recommendation:** Review the **Balanced Recovery** plan in the Recovery Center, which recovers exactly **${curr}${overspend}** to restore your budget to safe standing while preserving all **MUST_DO** sights.

Feel free to ask about specific modifications or compare the three available strategies!`;
}

function generateFollowUps(context: CopilotContext): string[] {
  return [
    'Why is my trip over budget?',
    'Compare my recovery strategies',
    'Explain the recommended hotel replacement',
    'How does transport optimization save money?',
  ];
}

